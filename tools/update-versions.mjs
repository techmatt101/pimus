#!/usr/bin/env node
// Refreshes every upstream version pin to the latest release. Run it with
// `make update-versions`, review the diff, then `make test` and provision.
//
// Three upstreams are pinned:
//   - linux-voice-assistant: voice_assistant_version in the inventory, from
//     the latest GitHub release tag.
//   - sendspin: sendspin_version in the inventory, from the latest PyPI
//     release.
//   - xvf_host (reSpeaker XVF3800 host control): that repository publishes no
//     releases or tags, so the pin is the latest master commit plus per-file
//     sha256 checksums, generated into ansible/roles/smartamp/vars/main.yml.
//
// Controller npm dependencies are not touched: they follow the pnpm flow in
// CLAUDE.md (pin in both package.json files, pnpm install, audit). The tool
// ends with `pnpm outdated` so those show up in the same place.

import {createHash} from 'node:crypto'
import {execFileSync} from 'node:child_process'
import {mkdir, readFile, writeFile} from 'node:fs/promises'
import {dirname} from 'node:path'
import {fileURLToPath} from 'node:url'

const INVENTORY = fileURLToPath(new URL('../ansible/inventory/group_vars/all.yml', import.meta.url))
const GENERATED_VARS = fileURLToPath(new URL('../ansible/roles/smartamp/vars/main.yml', import.meta.url))

const RESPEAKER_REPO = 'respeaker/reSpeaker_XVF3800_USB_4MIC_ARRAY'
// The rpi_64bit host-control set: the binary and the companion files it loads
// beside itself. The separate xvf_i2c_dfu firmware-update binary is excluded.
const RESPEAKER_FILES = [
    'xvf_host',
    'libcommand_map.so',
    'libdevice_usb.so',
    'libdevice_i2c.so',
    'transport_config.yaml',
    'dfu_cmds.yaml',
]

async function fetchOk(url, accept) {
    const response = await fetch(url, {headers: {accept, 'user-agent': 'pimus-update-versions'}})
    if (!response.ok) throw new Error(`${url} answered ${response.status} ${response.statusText}`)
    return response
}

const fetchJson = async (url) => (await fetchOk(url, 'application/vnd.github+json')).json()

async function latestGithubRelease(repository) {
    const release = await fetchJson(`https://api.github.com/repos/${repository}/releases/latest`)
    return String(release.tag_name).replace(/^v/, '')
}

async function latestPypiRelease(project) {
    const listing = await fetchJson(`https://pypi.org/pypi/${project}/json`)
    return String(listing.info.version)
}

/** Updates one `key: "value"` line in the inventory, reporting the change. */
async function pinInventory(key, version) {
    const inventory = await readFile(INVENTORY, 'utf8')
    const line = new RegExp(`^${key}: "([^"]*)"$`, 'm')
    const current = inventory.match(line)?.[1]
    if (current === undefined) throw new Error(`${key} not found in ${INVENTORY}`)
    if (current === version) {
        console.log(`${key}: ${current} is already the latest`)
        return false
    }
    await writeFile(INVENTORY, inventory.replace(line, `${key}: "${version}"`))
    console.log(`${key}: ${current} -> ${version}`)
    return true
}

async function pinRespeakerHostControl() {
    const commit = (await fetchJson(`https://api.github.com/repos/${RESPEAKER_REPO}/commits/master`)).sha
    const current = await readFile(GENERATED_VARS, 'utf8').catch(() => '')
    if (current.includes(`respeaker_host_control_commit: "${commit}"`)) {
        console.log(`respeaker_host_control_commit: ${commit.slice(0, 12)} is already the latest`)
        return
    }
    const checksums = []
    for (const name of RESPEAKER_FILES) {
        const url = `https://raw.githubusercontent.com/${RESPEAKER_REPO}/${commit}/host_control/rpi_64bit/${name}`
        const body = Buffer.from(await (await fetchOk(url, '*/*')).arrayBuffer())
        checksums.push(`  ${name}: "${createHash('sha256').update(body).digest('hex')}"`)
    }
    await mkdir(dirname(GENERATED_VARS), {recursive: true})
    await writeFile(GENERATED_VARS, [
        '---',
        '# Generated by tools/update-versions.mjs (make update-versions); do not edit.',
        '# The reSpeaker repository publishes no releases or tags, so the xvf_host',
        '# tool is pinned to a master commit with per-file sha256 checksums.',
        `respeaker_host_control_commit: "${commit}"`,
        'respeaker_host_control_checksums:',
        ...checksums,
        '',
    ].join('\n'))
    console.log(`respeaker_host_control_commit: -> ${commit.slice(0, 12)} (${RESPEAKER_FILES.length} checksums)`)
}

if (await pinInventory('voice_assistant_version', await latestGithubRelease('OHF-Voice/linux-voice-assistant'))) {
    console.log('  (review the wake-model list commented above it; models ship with the release)')
}
await pinInventory('sendspin_version', await latestPypiRelease('sendspin'))
await pinRespeakerHostControl()

console.log('\nnpm dependencies follow the pnpm flow in CLAUDE.md; currently outdated:')
try {
    console.log(execFileSync('pnpm', ['outdated', '--recursive'], {encoding: 'utf8'}))
} catch (error) {
    // pnpm exits non-zero when anything is outdated; that listing is the point.
    console.log(error.stdout || `  (pnpm outdated failed: ${error.message})`)
}
